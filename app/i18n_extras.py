def apply_auth_packs(strings: dict[str, dict[str, str]]) -> None:
    for lang, pack in AUTH_PACKS.items():
        if lang in strings:
            strings[lang].update(pack)
    for lang, pack in HELP_UI_PACKS.items():
        if lang in strings:
            strings[lang].update(pack)
    for lang, pack in TEAMS_BULK_PACKS.items():
        if lang in strings:
            strings[lang].update(pack)
    # Cualquier clave que aún falte en pt/fr/it/de/en: inglés, luego catalán
    en = strings.get("en", {})
    ca = strings.get("ca", {})
    for lang, dst in strings.items():
        if lang in {"ca", "es"}:
            continue
        for k, v in en.items():
            dst.setdefault(k, v)
        for k, v in ca.items():
            dst.setdefault(k, v)
