from app.i18n_extras import apply_auth_packs

apply_auth_packs(STRINGS)


def normalize_lang(code: str | None) -> str:
    c = (code or "").strip().lower()
    if c in LANGUAGES:
        return c
    upper = (code or "").strip().upper()
    for lang, (_label, mark) in LANGUAGES.items():
        if mark == upper:
            return lang
    return DEFAULT_LANG


def get_lang(request: Request) -> str:
    return normalize_lang(request.session.get("lang"))


def set_lang(request: Request, code: str) -> str:
    lang = normalize_lang(code)
    request.session["lang"] = lang
    return lang


def translate(lang: str, key: str) -> str:
    lang = normalize_lang(lang)
    return (
        STRINGS.get(lang, {}).get(key)
        or STRINGS.get("en", {}).get(key)
        or STRINGS[DEFAULT_LANG].get(key)
        or key
    )


def t_for(request: Request):
    lang = get_lang(request)

    def _t(key: str) -> str:
        return translate(lang, key)

    return _t


def weekdays(lang: str) -> list[str]:
    return [translate(lang, f"wd_{i}") for i in range(7)]


def weekdays_short(lang: str) -> list[str]:
    return [translate(lang, f"wd_s_{i}") for i in range(7)]


def i18n_context(request: Request) -> dict:
    lang = get_lang(request)
    return {
        "lang": lang,
        "langs": LANGUAGES,
        "t": t_for(request),
        "weekdays": weekdays(lang),
    }
